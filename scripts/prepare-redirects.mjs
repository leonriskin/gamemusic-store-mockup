/**
 * Writes _redirects for the current Netlify deploy context.
 * - production: under-construction rewrite (riskintracks.com stays gated)
 * - dev / previews / branch deploys: no construction redirect (full site + contact form)
 *
 * Netlify Dev reads _redirects from disk without running this script, so local
 * _redirects stays comment-only and localhost:8888 serves index.html.
 */
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const context = process.env.CONTEXT || 'dev';

const header = `# Riskin Tracks — site mode (generated by scripts/prepare-redirects.mjs)
# Context: ${context}
#
# Go live on production: remove the construction block in prepare-redirects.mjs
# (or skip writing redirects for production), then redeploy.
#
`;

const productionRedirects = `# Allow static assets (logo on under-construction page)
/assets/*    /assets/:splat    200

# Construction mode — forced rewrite for all other paths
/*    /under-construction.html    200!
`;

const devComment = `# No construction redirect — full store (index.html + contact form).
`;

const body = context === 'production' ? productionRedirects : devComment;

writeFileSync(join(root, '_redirects'), header + body, 'utf8');
console.log(`prepare-redirects: CONTEXT=${context} → ${context === 'production' ? 'construction mode' : 'full site'}`);
